/**
 * A label (with optional [supportingText]) and a Material 3 [Switch] on a row.
 * The whole row is tappable, not just the switch.
 */
@Composable
fun SwitchRow(
    label: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit,
    modifier: Modifier = Modifier,
    supportingText: String? = null,
    enabled: Boolean = true,
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .clickable(enabled = enabled) { onCheckedChange(!checked) }
            .padding(vertical = 6.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Text(
                text = label,
                style = MaterialTheme.typography.bodyLarge,
                color = MaterialTheme.colorScheme.onSurface,
            )
            if (supportingText != null) {
                Text(
                    text = supportingText,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
        Spacer(Modifier.width(12.dp))
        Switch(checked = checked, onCheckedChange = onCheckedChange, enabled = enabled)
    }
}

@Preview(name = "SwitchRow")
@Composable
private fun SwitchRowPreview() {
    PreviewContainer(darkTheme = true) {
        var on by remember { mutableStateOf(true) }
        SwitchRow(
            label = "Share over network",
            supportingText = "Send dropped markers as CoT",
            checked = on,
            onCheckedChange = { on = it },
        )
    }
}
